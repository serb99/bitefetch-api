#!/usr/bin/env node
// Generates small, readable DBML views from the full schema.dbml.
//
// Usage:  node docs/design/scripts/dbml-views.js docs/design/database/schema.dbml docs/design/database/views
//
// Output (in the output folder):
//   00-overview.dbml      all tables, only primary/foreign key columns -> shows the relationships
//   1-identity.dbml ...   one file per TableGroup, all columns of that group;
//                         tables it points to in other groups appear as grey stubs with just the linked
//                         columns (only outgoing relationships; incoming ones show in the other group's view)
//
// schema.dbml stays the single source of truth. The views are generated: never edit them,
// re-run this script after changing the schema.

const fs = require("fs");
const path = require("path");

const [, , input = "docs/design/database/schema.dbml", outDir = "docs/design/database/views"] = process.argv;
const lines = fs.readFileSync(input, "utf8").split(/\r?\n/);

const stripQuoted = (s) => s.replace(/'[^']*'|"[^"]*"|`[^`]*`/g, "");

// ---------- parse ----------
const enums = {}; // name -> [values]
const tables = {}; // name -> {columns:[{name,type,pk,unique,notNull,increment}]}
const tableOrder = [];
const refs = [];
const groups = {}; // name -> [tables]
const groupOrder = [];

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  let m = line.match(/^Enum (\w+) \{/);
  if (m) {
    const values = [];
    for (i++; i < lines.length && !/^\}/.test(lines[i]); i++) {
      const v = lines[i].trim().replace(/\[.*\]$/, "").trim();
      if (v && !v.startsWith("//")) values.push(v);
    }
    enums[m[1]] = values;
    continue;
  }

  m = line.match(/^Table (\w+) \{/);
  if (m) {
    const t = { name: m[1], columns: [] };
    let inColumns = true;
    let inIndexes = false;
    for (i++; i < lines.length && !/^\}/.test(lines[i]); i++) {
      const l = lines[i];
      if (/^\s*indexes \{/.test(l)) { inColumns = false; inIndexes = true; continue; }
      if (/^\s*Note:/.test(l)) {
        inColumns = false; inIndexes = false;
        // skip a multi-line ''' note
        if (/'''/.test(l) && (l.match(/'''/g) || []).length === 1) {
          for (i++; i < lines.length && !/'''/.test(lines[i]); i++);
        }
        continue;
      }
      if (inIndexes) {
        const im = stripQuoted(l).match(/^\s*\(([^)]*)\)\s*\[([^\]]*)\]/);
        if (im && /\bpk\b/.test(im[2])) {
          im[1].split(",").map((s) => s.trim()).forEach((c) => {
            const col = t.columns.find((x) => x.name === c);
            if (col) col.pk = true;
          });
        }
        continue;
      }
      if (!inColumns) continue;
      if (!l.trim() || l.trim().startsWith("//")) continue;
      const cm = l.match(/^\s+(\w+)\s+([^\s\[]+)\s*(\[.*\])?\s*$/);
      if (cm) {
        const settings = stripQuoted(cm[3] || "");
        t.columns.push({
          name: cm[1],
          type: cm[2],
          pk: /\bpk\b/.test(settings),
          unique: /\bunique\b/.test(settings),
          notNull: /not null/.test(settings),
          increment: /\bincrement\b/.test(settings),
        });
      }
    }
    tables[t.name] = t;
    tableOrder.push(t.name);
    continue;
  }

  m = line.match(/^Ref: (\w+)\.(\w+) ([<>-]) (\w+)\.(\w+)/);
  if (m) {
    refs.push({ t1: m[1], c1: m[2], op: m[3], t2: m[4], c2: m[5] });
    continue;
  }

  m = line.match(/^TableGroup (\w+) \{/);
  if (m) {
    const members = [];
    for (i++; i < lines.length && !/^\}/.test(lines[i]); i++) {
      const v = lines[i].trim();
      if (v && !v.startsWith("//")) members.push(v);
    }
    groups[m[1]] = members;
    groupOrder.push(m[1]);
  }
}

// ---------- emit helpers ----------
function colLine(c, withFlags = true) {
  const flags = [];
  if (c.pk) flags.push("pk");
  if (c.increment) flags.push("increment");
  if (c.unique) flags.push("unique");
  if (c.notNull && !c.pk) flags.push("not null");
  return "  " + c.name + " " + c.type + (withFlags && flags.length ? " [" + flags.join(", ") + "]" : "");
}

function tableBlock(name, cols, extra = "") {
  return "Table " + name + (extra ? " " + extra : "") + " {\n" + cols.map((c) => colLine(c)).join("\n") + "\n}\n";
}

function refLine(r) {
  return "Ref: " + r.t1 + "." + r.c1 + " " + r.op + " " + r.t2 + "." + r.c2;
}

function groupBlock(name) {
  return "TableGroup " + name + " {\n" + groups[name].map((t) => "  " + t).join("\n") + "\n}\n";
}

const header = (title) =>
  "// " + title + "\n// GENERATED by docs/design/scripts/dbml-views.js from schema.dbml. Do not edit; re-run the script.\n\n";

fs.mkdirSync(outDir, { recursive: true });

// ---------- overview: keys only ----------
const refCols = new Set();
refs.forEach((r) => { refCols.add(r.t1 + "." + r.c1); refCols.add(r.t2 + "." + r.c2); });

let overview = header("BiteFetch - overview: primary and foreign keys only");
tableOrder.forEach((n) => {
  const cols = tables[n].columns.filter((c) => c.pk || refCols.has(n + "." + c.name));
  overview += tableBlock(n, cols) + "\n";
});
overview += refs.map(refLine).join("\n") + "\n\n";
overview += groupOrder.map(groupBlock).join("\n");
fs.writeFileSync(path.join(outDir, "00-overview.dbml"), overview);

// ---------- one view per group ----------
groupOrder.forEach((g, idx) => {
  const members = new Set(groups[g]);
  // Only relationships that start in this group (what the group depends on).
  // Links coming in from other groups are shown in those groups' own views.
  const kept = refs.filter((r) => members.has(r.t1));

  // stubs: tables outside the group that are linked to it
  const stubCols = {}; // table -> Set(col)
  kept.forEach((r) => {
    [[r.t1, r.c1], [r.t2, r.c2]].forEach(([t, c]) => {
      if (!members.has(t)) (stubCols[t] = stubCols[t] || new Set()).add(c);
    });
  });

  // enums used by the group's tables
  const usedEnums = new Set();
  groups[g].forEach((n) => tables[n].columns.forEach((c) => { if (enums[c.type]) usedEnums.add(c.type); }));

  let out = header("BiteFetch - " + g.replace(/_/g, " ") + " (grey tables belong to other groups)");
  Object.keys(enums).filter((e) => usedEnums.has(e)).forEach((e) => {
    out += "Enum " + e + " {\n" + enums[e].map((v) => "  " + v).join("\n") + "\n}\n";
  });
  out += "\n";
  groups[g].forEach((n) => { out += tableBlock(n, tables[n].columns) + "\n"; });
  Object.keys(stubCols).forEach((n) => {
    const cols = tables[n].columns.filter((c) => c.pk || stubCols[n].has(c.name));
    out += tableBlock(n, cols, "[headercolor: #7a7f87]") + "\n";
  });
  out += kept.map(refLine).join("\n") + "\n\n";
  out += groupBlock(g);
  fs.writeFileSync(path.join(outDir, idx + 1 + "-" + g.replace(/_/g, "-") + ".dbml"), out);
});

console.log("Wrote " + (groupOrder.length + 1) + " view files to " + outDir);
console.log("Tables: " + tableOrder.length + ", refs: " + refs.length + ", groups: " + groupOrder.length);
